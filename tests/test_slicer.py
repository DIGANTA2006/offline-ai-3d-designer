"""Safety regression tests for the CuraEngine adapter."""

import trimesh

from ai3d_designer.slicing.slicer import SliceSettings, Slicer


def test_slice_settings_reject_invalid_quality_and_percentages():
    settings = SliceSettings(layer_height=0, infill_density=101, nozzle_diameter=float("nan"))
    errors = settings.validate()

    assert any("layer_height" in error for error in errors)
    assert any("infill_density" in error for error in errors)
    assert any("nozzle_diameter" in error for error in errors)


def test_missing_cura_engine_never_writes_placeholder_gcode(tmp_path):
    model_path = tmp_path / "cube.stl"
    output_path = tmp_path / "cube.gcode"
    trimesh.creation.box(extents=(10, 10, 10)).export(model_path)

    slicer = Slicer(cura_engine_path="unused-test-path")
    slicer.cura_engine_path = None
    slicer.cura_available = False
    result = slicer.slice(str(model_path), str(output_path), SliceSettings())

    assert result.success is False
    assert not output_path.exists()
    assert any("No placeholder G-code" in error for error in result.errors)


def test_gcode_validator_rejects_old_preview_placeholder(tmp_path):
    path = tmp_path / "placeholder.gcode"
    path.write_text(
        "; Basic G-code generated by AI 3D Designer\n"
        "; This is a PREVIEW only - not for actual printing!\n"
        "G21\nG28\n; Layer 1/2\nG1 X10 Y10 Z0.2\nG1 X20 E1\n",
        encoding="utf-8",
    )

    result = Slicer(cura_engine_path="unused-test-path").validate_gcode(str(path))
    assert result["valid"] is False
    assert "Placeholder/preview-only" in result["error"]


def test_gcode_validator_accepts_minimal_layered_extrusion(tmp_path):
    path = tmp_path / "minimal.gcode"
    path.write_text(
        ";FLAVOR:Marlin\n"
        ";LAYER_COUNT:1\n"
        "G21\nM104 S200\nG28\n;LAYER:0\n"
        "G1 X1 Y1 Z0.2 F1500\n"
        "G1 X2 Y1 E0.5 F1500\n"
        "M104 S0\n",
        encoding="utf-8",
    )

    result = Slicer(cura_engine_path="unused-test-path").validate_gcode(str(path))
    assert result["valid"] is True
    assert result["stats"]["has_home"] is True
    assert result["stats"]["has_extrusion"] is True
    assert result["stats"]["layers"] == 1
