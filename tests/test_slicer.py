    slicer = Slicer(cura_engine_path="/fake")
    
    gcode = (
        ";TIME:3600\n"
        ";LAYER_COUNT:10\n"
        ";Filament used: 5000mm, 15.5g\n"
        "G21\nG28\n;LAYER:0\nG1 X10 Y10 Z0.2 E1\n"
    )
    path = tmp_path / "meta.gcode"
    path.write_text(gcode)
    
    metadata = slicer._parse_gcode_metadata(str(path))
